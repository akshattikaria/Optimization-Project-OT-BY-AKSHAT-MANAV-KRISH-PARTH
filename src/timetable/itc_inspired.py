"""Synthetic generator of ITC-inspired curriculum timetabling instances.

The instances borrow the *structure* of ITC-2007 Track 3 (Curriculum-Based
Course Timetabling): curricula as student cohorts, courses with several weekly
lectures, a few courses shared between curricula and rooms of different
capacities.  They are generated by this module with a seeded random number
generator and expressed in this project's own model (teacher eligibility,
weekly/daily teaching limits, the three objectives f1-f3).

They are **not** the official ITC-2007 instances: no competition ``.ctt`` file
is read or converted, the data differ from ``comp01`` and the competition's
soft-constraint penalties are not used.  Results on these instances must not
be compared with published ITC-2007 results or reported as ITC benchmark
results.

Structure reference:
M. Di Gaspero, B. McCollum, A. Schaerf, "The Second International Timetabling
Competition (ITC-2007): Curriculum-based Course Timetabling (Track 3)", 2007.
"""
from __future__ import annotations

from collections import defaultdict
import random

from .evaluation import evaluate
from .greedy import construct
from .model import Faculty, Group, Offering, Problem, Room, Schedule, validate_problem


def generate_itc_inspired_instance(
    name: str = "ITC_inspired_CBCTT_01",
    num_curricula: int = 5,
    courses_per_curriculum: int = 5,
    num_rooms: int = 6,
    num_faculty: int = 12,
    seed: int = 2007,
) -> tuple[Problem, Schedule]:
    """Generate a synthetic ITC-inspired instance together with a feasible certificate.

    Curricula have weekly course loads of about 15-20 periods out of the 30
    teaching periods, which avoids saturating a cohort while leaving real
    room-fit, gap and workload trade-offs.  The certificate is built by the
    constructive heuristic and independently checked; it shows feasibility only.
    """
    rng = random.Random(seed)

    days = ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday")
    periods_per_day = 7
    lunch_periods = (3,)  # Period index 3 is lunch (30 teaching slots per week)
    teaching_slots_count = len(days) * (periods_per_day - len(lunch_periods))

    # 1. Curricula (Atomic Cohorts)
    group_sizes = [25, 30, 45, 50, 35, 60]
    groups = tuple(
        Group(f"Curriculum_{i+1:02d}", group_sizes[i % len(group_sizes)])
        for i in range(num_curricula)
    )

    # 2. Rooms with heterogeneous capacities
    room_caps = [35, 50, 60, 75, 50, 90, 40, 65]
    rooms = tuple(
        Room(
            id=f"Room_{i+1:02d}",
            capacity=room_caps[i % len(room_caps)],
            kind="classroom",
            unavailable=(),
        )
        for i in range(num_rooms)
    )

    # 3. Faculty
    faculty_list = []
    for i in range(num_faculty):
        fid = f"Prof_{i+1:02d}"
        faculty_list.append(Faculty(
            id=fid,
            max_weekly=16,
            max_daily=4,
            unavailable=(),
        ))
    faculty = tuple(faculty_list)

    # 4. Generate courses per curriculum respecting weekly student workload limits
    # As in CB-CTT, a curriculum takes ~4-6 courses of 3-4 lectures each (~15-20 periods)
    offerings = []
    course_counter = 1
    prof_loads = defaultdict(int)

    for g in groups:
        # 4 courses of 3 sessions + 1 course of 4 sessions = 16 sessions / week
        for c_idx in range(courses_per_curriculum):
            cid = f"Course_{course_counter:02d}"
            sessions = 4 if c_idx == 0 else 3

            # Pick least-loaded professors as primary and backup
            sorted_profs = sorted(faculty, key=lambda f: prof_loads[f.id])
            primary_prof = sorted_profs[0].id
            backup_prof = sorted_profs[1].id
            prof_loads[primary_prof] += sessions

            offerings.append(Offering(
                id=cid,
                groups=(g.id,),
                eligible_faculty=(primary_prof, backup_prof),
                sessions=sessions,
                duration=1,
                room_kind="classroom",
                distinct_days=True,
            ))
            course_counter += 1

    # Add 2 shared elective courses shared between adjacent curricula
    if num_curricula >= 2:
        for pair_idx in range(min(2, num_curricula - 1)):
            cid = f"Course_Shared_{pair_idx+1:02d}"
            sorted_profs = sorted(faculty, key=lambda f: prof_loads[f.id])
            primary_prof = sorted_profs[0].id
            backup_prof = sorted_profs[1].id
            prof_loads[primary_prof] += 2
            offerings.append(Offering(
                id=cid,
                groups=(groups[pair_idx].id, groups[pair_idx + 1].id),
                eligible_faculty=(primary_prof, backup_prof),
                sessions=2,
                duration=1,
                room_kind="classroom",
                distinct_days=True,
            ))

    problem = Problem(
        name=name,
        days=days,
        periods_per_day=periods_per_day,
        lunch_periods=lunch_periods,
        groups=groups,
        rooms=rooms,
        faculty=faculty,
        offerings=tuple(offerings),
        metadata={
            "source": "Synthetic instance in the style of ITC-2007 CB-CTT; not an official ITC benchmark instance",
            "type": "Curriculum-based course timetabling (ITC-inspired structure)",
            "curricula": num_curricula,
            "courses": len(offerings),
            "teaching_periods_per_week": teaching_slots_count,
            "seed": seed,
        },
    )
    validate_problem(problem)

    # Build and verify a feasible certificate
    certificate = construct(problem, rng, randomized=False)
    ev = evaluate(problem, certificate)
    if not ev.feasible:
        # If deterministic failed, try randomized seeds to guarantee planted certificate
        for attempt in range(1, 100):
            certificate = construct(problem, random.Random(seed + attempt * 17), randomized=True)
            if evaluate(problem, certificate).feasible:
                break

    assert evaluate(problem, certificate).feasible, "Failed to build a feasible certificate for the ITC-inspired instance"
    return problem, certificate
