"""Multi-Objective Evolutionary Algorithm based on Decomposition (MOEA/D).

This implementation decomposes the 3-objective college timetabling problem into N
scalar optimization subproblems using Tchebycheff scalarization (and optional
augmented Tchebycheff or weighted sum). Each subproblem maintains a solution and
collaborates with a local neighborhood of weight vectors.

Key Optimization Techniques (OT) Concepts:
------------------------------------------
1. Decomposition vs. Dominance-based Selection:
   Unlike NSGA-II, which sorts the whole population using Pareto dominance and
   crowding distance, MOEA/D optimizes N scalar subproblems simultaneously. Each
   subproblem searches in a distinct direction in objective space, naturally
   maintaining population diversity across the trade-off surface.

2. Tchebycheff Scalarization:
   g^te(x | lambda, z*) = max_{j=1..3} { lambda_j * |f_j(x) - z_j*| / s_j }
   where z* is the reference (ideal) point and s_j are scale normalizers.
   Unlike Weighted Sum (sum lambda_j * f_j), which CANNOT find non-convex Pareto
   optimal points (unsupported solutions), Tchebycheff contours are L-shaped
   orthogonal cones capable of capturing ANY Pareto-optimal point regardless of
   the curvature or non-convexity of the true front.

3. Neighborhood Information Sharing:
   Subproblems are ordered by weight vector proximity. Offspring generated by
   subproblem i are evaluated against all neighbors in B(i) and replace inferior
   neighbor solutions, drastically speeding up convergence while respecting
   evaluation budgets.
"""
from __future__ import annotations

import math
from math import isfinite
import random
from time import perf_counter
from typing import Callable, Sequence

from .evaluation import Evaluation, evaluate
from .feasible import FeasibleNeighborhood
from .greedy import construct
from .metrics import constraint_dominates, dominates, objective_scales
from .model import Problem, Schedule, validate_problem
from .nsga2 import Individual, SearchResult


def generate_simplex_weights(n: int, dim: int = 3, seed: int = 0) -> list[tuple[float, ...]]:
    """Generate n well-distributed weight vectors on the unit simplex sum(w_i) = 1.
    
    Uses Das & Dennis simplex-lattice design, adjusting or subsampling to return
    exactly n well-spaced weight vectors with positive coordinates.
    """
    if dim != 3:
        raise ValueError("Currently dim=3 is supported for 3-objective timetabling")
    if n < 2:
        raise ValueError("n must be >= 2")

    # Find lattice parameter H such that (H+1)*(H+2)//2 >= n
    h = 1
    while (h + 1) * (h + 2) // 2 < n:
        h += 1

    lattice: list[tuple[float, float, float]] = []
    for i in range(h + 1):
        for j in range(h + 1 - i):
            k = h - i - j
            lattice.append((max(i / h, 1e-4), max(j / h, 1e-4), max(k / h, 1e-4)))

    # Normalize so coordinates sum to 1.0
    normalized = []
    for w in lattice:
        tot = sum(w)
        normalized.append((w[0] / tot, w[1] / tot, w[2] / tot))

    if len(normalized) == n:
        return normalized

    # If lattice has more than n points, subsample deterministically using max-min distance
    rng = random.Random(seed)
    # Always include the 3 extreme points closest to unit vectors
    selected = [
        max(normalized, key=lambda w: w[0]),
        max(normalized, key=lambda w: w[1]),
        max(normalized, key=lambda w: w[2]),
    ]
    remaining = [w for w in normalized if w not in selected]

    while len(selected) < n and remaining:
        # Pick point with maximum minimum Euclidean distance to already selected
        best_pt = None
        best_dist = -1.0
        for pt in remaining:
            d = min(math.dist(pt, s) for s in selected)
            if d > best_dist:
                best_dist = d
                best_pt = pt
        if best_pt is not None:
            selected.append(best_pt)
            remaining.remove(best_pt)

    # If still fewer (e.g. n was larger than lattice), add Dirichlet/simplex random points
    while len(selected) < n:
        raw = [rng.expovariate(1.0) for _ in range(3)]
        tot = sum(raw)
        selected.append((raw[0] / tot, raw[1] / tot, raw[2] / tot))

    return selected[:n]


def tchebycheff(
    objectives: Sequence[float],
    weights: Sequence[float],
    ideal: Sequence[float],
    scales: Sequence[float],
    rho: float = 1e-4,
) -> float:
    """Augmented Tchebycheff scalarization function.
    
    g^te(f | lambda, z*) = max_j { lambda_j * (f_j - z_j*) / s_j } + rho * sum_j { lambda_j * (f_j - z_j*) / s_j }
    """
    diffs = [max(0.0, (f - z)) / s for f, z, s in zip(objectives, ideal, scales)]
    max_term = max(w * diff for w, diff in zip(weights, diffs))
    aug_term = rho * sum(w * diff for w, diff in zip(weights, diffs))
    return max_term + aug_term


def weighted_sum(
    objectives: Sequence[float],
    weights: Sequence[float],
    scales: Sequence[float],
) -> float:
    """Linear weighted sum scalarization: sum_j { lambda_j * f_j / s_j }."""
    return sum(w * (f / s) for w, f, s in zip(weights, objectives, scales))


def moead(
    problem: Problem,
    seed: int = 0,
    population_size: int = 24,
    max_evaluations: int = 480,
    time_limit: float | None = None,
    neighborhood_size: int = 6,
    scalarization: str = "tchebycheff",
    max_replacements: int = 2,
    use_faculty_search: bool = True,
    evaluator: Callable[[Problem, Schedule], Evaluation] | None = None,
    faculty_every: int = 6,
    faculty_nodes: int = 12000,
    progress: dict | None = None,
) -> SearchResult:
    """Decomposition-based multi-objective optimization (MOEA/D) for timetabling.
    
    Parameters:
        problem: Target timetable problem instance.
        seed: Random seed for initialization and neighborhood moves.
        population_size: Number of subproblems / weight vectors.
        max_evaluations: Total budget of full candidate evaluations.
        time_limit: Optional wall-clock second limit.
        neighborhood_size: Number of closest weight vectors in each subproblem's neighborhood.
        scalarization: 'tchebycheff', 'weighted_sum', or 'augmented_tchebycheff'.
        max_replacements: Maximum number of neighbor solutions an offspring can replace.
        use_faculty_search: Whether to periodically apply bounded faculty reassignment.
        evaluator: Counted objective evaluator.
    """
    validate_problem(problem)
    if type(population_size) is not int or population_size < 2:
        raise ValueError("population_size must be an integer >= 2")
    if type(max_evaluations) is not int or max_evaluations < 1:
        raise ValueError("max_evaluations must be a positive integer")
    if time_limit is not None and (not isfinite(time_limit) or time_limit <= 0):
        raise ValueError("time_limit must be finite and positive")
    if scalarization not in {"tchebycheff", "augmented_tchebycheff", "weighted_sum"}:
        raise ValueError("scalarization must be 'tchebycheff', 'augmented_tchebycheff', or 'weighted_sum'")

    evaluator = evaluate if evaluator is None else evaluator
    rng = random.Random(seed)
    started = perf_counter()
    deadline = started + time_limit if time_limit is not None else float("inf")
    neighborhood = FeasibleNeighborhood(problem)
    scales = objective_scales(problem)

    # 1. Generate weight vectors on the 3D unit simplex
    weights = generate_simplex_weights(population_size, dim=3, seed=seed)
    t_size = min(neighborhood_size, population_size)

    # 2. Compute Euclidean distance neighborhoods B(i)
    neighborhoods: list[list[int]] = []
    for i, w_i in enumerate(weights):
        dists = [(math.dist(w_i, w_j), j) for j, w_j in enumerate(weights)]
        dists.sort(key=lambda item: item[0])
        neighborhoods.append([j for _, j in dists[:t_size]])

    archive: list[Individual] = []
    population: list[Individual] = []
    history = []
    calls = feasible_calls = late_calls = initial_attempts = 0
    proposals = noops = restarts = faculty_calls = faculty_search_nodes = faculty_changes = 0
    offspring_feasible = offspring_evaluated = 0
    replacements_done = 0
    neighborhood_calls = final_noops = 0
    minimum_violation: int | None = None
    best: Individual | None = None
    seen: set[Schedule] = set()

    # Dynamic ideal point z* = (min f1, min f2, min f3)
    ideal = [float("inf"), float("inf"), float("inf")]

    def remaining() -> bool:
        return calls < max_evaluations and perf_counter() < deadline

    def eval_scalar(ind: Individual, weight: tuple[float, ...]) -> float:
        objs = ind.evaluation.objectives
        if scalarization == "weighted_sum":
            return weighted_sum(objs, weight, scales)
        rho = 1e-3  # Augmented Tchebycheff eliminates weak Pareto points
        return tchebycheff(objs, weight, ideal, scales, rho=rho)

    def diagnostics() -> dict:
        return {
            "algorithm": "moead",
            "scalarization": scalarization,
            "population_size": population_size,
            "neighborhood_size": t_size,
            "use_faculty_search": use_faculty_search,
            "initial_attempts": initial_attempts,
            "variation_proposals": proposals,
            "replacements_done": replacements_done,
            "ideal_point": list(ideal) if ideal[0] != float("inf") else None,
            "offspring_evaluated": offspring_evaluated,
            "offspring_feasible": offspring_feasible,
            "faculty_search_calls": faculty_calls,
            "faculty_search_nodes": faculty_search_nodes,
            "faculty_changes": faculty_changes,
        }

    def counted(schedule: Schedule) -> Individual | None:
        nonlocal calls, feasible_calls, late_calls, minimum_violation, best, ideal
        if not remaining():
            return None
        ev = evaluator(problem, schedule)
        calls += 1
        candidate = Individual(schedule, ev)
        if perf_counter() > deadline:
            late_calls += 1
            return None
        seen.add(schedule)
        minimum_violation = ev.violation if minimum_violation is None else min(minimum_violation, ev.violation)
        if best is None or constraint_dominates(ev.objectives, best.evaluation.objectives, ev.violation, best.evaluation.violation):
            best = candidate
        if ev.feasible:
            feasible_calls += 1
            # Update ideal reference point
            ideal[0] = min(ideal[0], ev.objectives[0])
            ideal[1] = min(ideal[1], ev.objectives[1])
            ideal[2] = min(ideal[2], ev.objectives[2])
            # Update external non-dominated Pareto archive
            if not any(old.evaluation.objectives == ev.objectives or dominates(old.evaluation.objectives, ev.objectives)
                       for old in archive):
                archive[:] = [old for old in archive if not dominates(ev.objectives, old.evaluation.objectives)]
                archive.append(candidate)
        if progress is not None:
            progress.update(diagnostics())
        return candidate

    # 3. Feasible intelligent initialization matching problem setup
    init_candidates: list[Individual] = []
    while len(init_candidates) < population_size and remaining() and initial_attempts < 4 * population_size:
        schedule = construct(problem, rng, randomized=initial_attempts > 0)
        initial_attempts += 1
        cand = counted(schedule)
        if cand is not None and cand.evaluation.feasible:
            init_candidates.append(cand)

    # Assign each subproblem the candidate that minimizes its scalarization function
    if init_candidates:
        population = [min(init_candidates, key=lambda c: eval_scalar(c, w)) for w in weights]
    else:
        population = init_candidates

    # Record generation 0
    history.append({
        "generation": 0,
        "evaluations": calls,
        "elapsed": perf_counter() - started,
        "feasible_fraction": 1.0 if population else 0.0,
        "evaluated_feasible_fraction": feasible_calls / calls if calls else 0.0,
        "min_violation": minimum_violation,
        "front": [list(x.evaluation.objectives) for x in archive],
    })

    # 4. Main MOEA/D Evolutionary Loop
    generation = 0
    while len(population) >= 2 and remaining():
        generation += 1
        for i in range(len(population)):
            if not remaining():
                break

            # Select parent from neighborhood B(i)
            neighbors = neighborhoods[i]
            parent_idx = rng.choice(neighbors)
            parent = population[parent_idx]
            proposals += 1

            # Propose feasibility-preserving move:
            # Subproblems prioritizing faculty balance or periodic step use faculty integer search
            w_i = weights[i]
            if use_faculty_search and (w_i[2] >= 0.25 or proposals % faculty_every == 0):
                from .faculty_search import faculty_reassign
                fac_diag = {}
                child_schedule = faculty_reassign(
                    problem, parent.schedule, rng, max_offerings=8,
                    max_nodes=faculty_nodes, diagnostics=fac_diag
                )
                faculty_calls += 1
                faculty_search_nodes += fac_diag.get("nodes", 0)
                faculty_changes += child_schedule != parent.schedule
            elif proposals % 31 == 0:
                child_schedule = construct(problem, rng, randomized=True)
                restarts += 1
            else:
                child_schedule = neighborhood.propose(parent.schedule, rng)
                neighborhood_calls += 1

            if child_schedule == parent.schedule:
                noops += 1
                child_schedule = neighborhood.propose(parent.schedule, rng)
                neighborhood_calls += 1
            final_noops += child_schedule == parent.schedule

            child = counted(child_schedule)
            if child is None:
                break
            offspring_evaluated += 1
            offspring_feasible += child.evaluation.feasible

            # Subproblem update using Tchebycheff scalarization
            if child.evaluation.feasible:
                # Update neighbor subproblems in B(i)
                replaced = 0
                perm_neighbors = list(neighbors)
                rng.shuffle(perm_neighbors)
                for j in perm_neighbors:
                    w_j = weights[j]
                    current_scalar = eval_scalar(population[j], w_j)
                    child_scalar = eval_scalar(child, w_j)
                    if child_scalar < current_scalar:
                        population[j] = child
                        replaced += 1
                        replacements_done += 1
                        if replaced >= max_replacements:
                            break

        history.append({
            "generation": generation,
            "evaluations": calls,
            "elapsed": perf_counter() - started,
            "feasible_fraction": 1.0,
            "evaluated_feasible_fraction": feasible_calls / calls if calls else 0.0,
            "min_violation": minimum_violation,
            "front": [list(x.evaluation.objectives) for x in archive],
        })

    metadata = diagnostics()
    metadata.update({
        "evaluated_feasible": feasible_calls,
        "minimum_violation": minimum_violation if minimum_violation is not None else 0,
        "calls": calls,
        "budget": max_evaluations,
    })
    best_sched = archive[0].schedule if archive else (best.schedule if best else None)
    return SearchResult(
        archive=[x.schedule for x in archive],
        history=history,
        evaluations=calls,
        runtime=perf_counter() - started,
        metadata=metadata,
        best_schedule=best_sched,
        population=[x.schedule for x in population],
    )
